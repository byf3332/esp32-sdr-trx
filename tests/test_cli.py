@pytest.mark.parametrize("build,doc", [(cli_rx.build_parser, "docs/espdr-rx.md"), (cli_tx.build_parser, "docs/espdr-tx.md")])
def test_the_command_reference_lists_every_option(build, doc):
    """docs/espdr-*.md are generated by scripts/gen-reference.py; the wording of argparse's help differs between Python versions, so the
    test only checks that every option is in the reference (regenerate it after changing a command line)."""
    import pathlib
    text = (pathlib.Path(__file__).resolve().parents[1] / doc).read_text()
    missing = [o for a in build()._actions for o in a.option_strings if o.startswith("--") and o not in text]
    assert not missing, f"{doc} lacks {missing}: run python scripts/gen-reference.py"


